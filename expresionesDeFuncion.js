//En teoría es una función que se declara como una variable "Expresión"

const suma = function(a, b) {  //Se declara una variable para dentro de ella escribir una función sin nombre, por lo que el nombre sería el de la variable.
    return a + b;  // Aquí, como siempre, dentro de los paréntesis aparece lo que se hace con los parámetros.
};

console.log(suma(2,3)) // Se llama igual que como si fuera una función normal.


