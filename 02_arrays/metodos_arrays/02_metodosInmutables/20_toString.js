// El método toString() convierte todos los elementos del array en una cadena separados por comas.
let colores = ["rojo", "verde", "azul"];
console.log(colores.toString()); // Imprime: rojo,verde,azul

// Usando toString en un array de números
let numeros = [1, 2, 3, 4, 5];
console.log(numeros.toString()); // Imprime: 1,2,3,4,5

// Resumen: El método toString() es útil para convertir un array en una cadena separada por comas.